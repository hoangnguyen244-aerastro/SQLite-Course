-- Тема 3, Задание 3: сохранить запрос в виде VIEW
-- Запускать в SQLiteStudio на РАБОЧЕЙ КОПИИ b9.db.
DROP VIEW IF EXISTS "Количество_сотрудников_по_отделам";

CREATE VIEW "Количество_сотрудников_по_отделам" AS
SELECT
    o.Отдел AS "Наименование отдела",
    COUNT(s.[Код сотрудника]) AS "Количество сотрудников"
FROM Отделы AS o
LEFT JOIN Сотрудники AS s
    ON s.[Код отдела] = o.[Код отдела]
GROUP BY o.[Код отдела], o.Отдел;

-- Проверка представления:
SELECT *
FROM "Количество_сотрудников_по_отделам"
ORDER BY "Наименование отдела";
